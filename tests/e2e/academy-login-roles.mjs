import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const base=process.env.ACADEMY_AUDIT_URL||'http://localhost:3217';
assert.ok(['127.0.0.1','localhost'].includes(new URL(base).hostname));
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1366,height:900}});
const page=await context.newPage();page.setDefaultTimeout(15000);
await page.goto(base+'/login');
await page.locator('button[type=submit]').click();
assert.equal(new URL(page.url()).pathname,'/login');
assert.equal(await page.locator('input:invalid').count(),2);
await page.locator('input[autocomplete=username]').fill('audit');
await page.locator('input[type=password]').fill('incorrect-audit-password');
await page.locator('button[type=submit]').click();
await page.getByRole('alert').waitFor();
await page.locator('input[type=password]').fill('local-audit-only');
await page.locator('button[type=submit]').click();
await page.waitForURL('**/group-config');
assert.equal((await context.request.get(base+'/api/auth/session')).status(),200);
await context.request.post(base+'/api/auth/logout');
await page.goto(base+'/login');
await page.locator('input[autocomplete=username]').fill('manual-audit');
await page.locator('input[type=password]').fill('manual-local-audit');
await page.locator('button[type=submit]').click();
await page.waitForURL('**/composer');
await page.locator('h1').waitFor();
assert.equal((await context.request.get(base+'/api/distribution')).status(),403);
assert.equal((await context.request.post(base+'/api/telegram/user-authorization',{data:{action:'cancel'}})).status(),403);
assert.equal((await context.request.get(base+'/api/composer/target-folders')).status(),200);
await page.goto(base+'/settings');
assert.equal(new URL(page.url()).pathname,'/composer');
assert.equal(await page.getByRole('button',{name:'加入队列',exact:true}).count(),0);
console.log('Login required fields, wrong password, admin login, logout and manual role restrictions passed');
await browser.close();
